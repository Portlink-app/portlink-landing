#!/usr/bin/env node
/**
 * check-font-hosts.mjs: no page, stylesheet or script the site ships may reach Google's font hosts.
 *
 *   node scripts/check-font-hosts.mjs            authored source: app, components, lib, hooks, public (prebuild, verify)
 *   node scripts/check-font-hosts.mjs --built    server HTML + every CSS/JS file under .next (postbuild)
 *   node scripts/check-font-hosts.mjs --live     portlink.app pages and the stylesheets they link
 *   node scripts/check-font-hosts.mjs --live https://deploy-preview-1--portlin-landing-2.netlify.app
 *
 * Exit 0 = pass, 1 = a Google font host is in shipped output, 2 = could not measure.
 *
 * ⛔ THE TRAP THIS GUARDS. Until 29.09.2026 app/globals.css began with three @import url()s to
 * fonts.googleapis.com. They never appeared in server HTML: Tailwind hoisted them to the top of the
 * built CSS chunk, so every page fetched Google's CSS and then fonts.gstatic.com woff2 files, 10 to
 * 12 requests before the consent banner could be answered, sending each visitor's IP to Google
 * (LG München I, 20.01.2022, 3 O 17493/20). check-consent-gate.mjs could not see it, because it
 * reads <script>/<link> tags in HTML and this lived in CSS. So this check reads the CSS.
 *
 * The fonts are self-hosted in app/_fonts/, generated by scripts/sync-fonts.mjs. That script, and
 * this one, are the only files allowed to name the hosts, which is why scripts/ is not scanned.
 * Unlike the consent gate this is not "after a yes": no consent category exists for fonts, so the
 * hosts are refused everywhere, always.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
// A URL, not a bare mention: prose that explains the rule ("never from fonts.gstatic.com") is fine,
// anything a browser could fetch is not. Covers https://, http:// and protocol-relative //.
const HOST = /(?:https?:)?\/\/fonts\.(?:googleapis|gstatic)\.com/g

function fail(message, code = 1) {
  console.error(`check:font-hosts: ${message}`)
  process.exit(code)
}

/** Every Google font URL in one file's text, with its line number. Empty = clean. */
function hits(text) {
  return [...text.matchAll(HOST)].map((m) => `line ${text.slice(0, m.index).split('\n').length}: ${text.slice(m.index, m.index + 160).split(/['")\s]/)[0]}`)
}

function walk(dir, keep, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, keep, out)
    else if (keep(entry.name)) out.push(full)
  }
  return out
}

function scan(files, base) {
  const bad = []
  for (const f of files) {
    const found = hits(fs.readFileSync(f, 'utf8'))
    if (found.length) bad.push(`${path.relative(base, f)}: ${found.join(', ')}`)
  }
  return bad
}

// Self-test first: a check that cannot see the host must not report a clean site.
if (!hits("@import url('https://fonts.googleapis.com/css2?family=Inter&display=swap');").length) fail('self-test: a CSS @import was not seen.', 2)
if (!hits('@import "https://fonts.googleapis.com/css2?family=Inter";').length) fail('self-test: the built (Tailwind-hoisted) @import form was not seen.', 2)
if (!hits('<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>').length) fail('self-test: a preconnect link was not seen.', 2)
if (!hits('src:url(//fonts.gstatic.com/s/inter/v20/a.woff2)').length) fail('self-test: a protocol-relative url() was not seen.', 2)
if (hits('/* served from this origin, never from fonts.googleapis.com */ src:url(../media/a.woff2)').length) fail('self-test: prose naming the host was refused.', 2)

const mode = process.argv.includes('--built') ? 'built' : process.argv.includes('--live') ? 'live' : 'source'

if (mode === 'source') {
  const shipped = /\.(tsx?|jsx?|mjs|css|html|json|svg|md)$/
  const files = ['app', 'components', 'lib', 'hooks', 'public'].flatMap((d) => walk(path.join(ROOT, d), (n) => shipped.test(n)))
  if (files.length < 20) fail(`only ${files.length} source files found; the scan is not looking where the site lives.`, 2)
  const bad = scan(files, ROOT)
  if (bad.length) fail(`a Google font URL is in authored source:\n  ${bad.join('\n  ')}\nSelf-host it through scripts/sync-fonts.mjs instead.`)
  console.log(`check:font-hosts source: no Google font URL in ${files.length} authored files; self-test passed.`)
} else if (mode === 'built') {
  const html = walk(path.join(ROOT, '.next/server/app'), (n) => n.endsWith('.html'))
  const css = walk(path.join(ROOT, '.next/static'), (n) => n.endsWith('.css'))
  const js = walk(path.join(ROOT, '.next/static'), (n) => n.endsWith('.js'))
  if (!html.length || !css.length) fail('build output is missing; run next build first.', 2)
  const bad = scan([...html, ...css, ...js], path.join(ROOT, '.next'))
  if (bad.length) fail(`a Google font URL is in the build, so every visitor's browser would call Google before consent:\n  ${bad.join('\n  ')}`)
  // Known positive: the self-hosted faces must be in the built CSS. Without them the scan above
  // passes on a site that silently lost its fonts, which is not the same thing as passing.
  const allCss = css.map((f) => fs.readFileSync(f, 'utf8')).join('\n')
  for (const family of ['Plus Jakarta Sans', 'Inter', 'JetBrains Mono']) {
    const face = new RegExp(`@font-face\\s*\\{[^}]*font-family:\\s*['"]?${family}['"]?[^}]*url\\((?:\\.\\.?/|/_next/)[^)]*\\.woff2\\)`)
    if (!face.test(allCss)) fail(`no self-hosted @font-face for ${family} in the built CSS; app/_fonts/fonts.css is not reaching the bundle.`, 2)
  }
  console.log(`check:font-hosts built: no Google font URL in ${html.length} pages, ${css.length} stylesheets, ${js.length} scripts; all three families self-hosted in the built CSS; self-test passed.`)
} else {
  const arg = process.argv[process.argv.indexOf('--live') + 1] ?? ''
  const base = arg.startsWith('http') ? arg.replace(/\/$/, '') : 'https://portlink.app'
  let bad = 0
  const sheets = new Map() // stylesheet url -> its hits, fetched once, reported on every page that links it
  for (const route of ['/', '/privacy/', '/contact/', '/team/', '/seatrade/']) {
    const res = await fetch(base + route)
    if (!res.ok) { console.log(`${base}${route}: HTTP ${res.status}`); bad++; continue }
    const page = await res.text()
    const found = hits(page)
    for (const [, href] of page.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"/g)) {
      const url = new URL(href, base + route).href
      if (!sheets.has(url)) sheets.set(url, hits(await (await fetch(url)).text()))
      found.push(...sheets.get(url).map((h) => `${url.replace(base, '')} ${h}`))
    }
    if (found.length) bad++
    console.log(`${base}${route}: ${found.length ? found.join(', ') : 'no Google font URL in the page or its stylesheets'}`)
  }
  if (!sheets.size) fail('no stylesheet was linked from any page; the live check measured nothing.', 2)
  if (bad) process.exit(1)
}
