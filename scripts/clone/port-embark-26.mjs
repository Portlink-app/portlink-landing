// Ports the Butter-structure Embark page from landing PR #26 (b25b2b2, archived as
// refs/archive/product-family-b25b2b2) into the /embark route: its <main> markup becomes a string
// module, asset paths move to public/clone/butter/, and its contact links become the site's demo
// action with funnel ids. Preview-only clone work: docs/PRODUCT-PAGES.md "Clone method".
//   node scripts/clone/port-embark-26.mjs   (run from the repo root; reads the archived commit)
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const html = execFileSync('git', ['show', 'b25b2b2:public/product-family/embark.html'], { encoding: 'utf8' })
let main = html.slice(html.indexOf('<main'), html.lastIndexOf('</main>') + 7)
main = main
  .replace(/^<main[^>]*>/, '').replace(/<\/main>$/, '')
  .replace(/<a id="skip-to-content"[^>]*>.*?<\/a>/, '')
  .replace(/<script[\s\S]*?<\/script>/g, '')
  .replaceAll('/product-family/assets/', '/clone/butter/assets/')
  .replaceAll('/product-family/media/', '/clone/butter/media/')
  .replaceAll('https://portlink.app/privacy/', '/privacy/')
let n = 0
const ids = ['nav', 'close', 'footer']
main = main.replace(/href="mailto:pilot@portlink\.app\?subject=Embark%20demo%20enquiry"/g, () => `href="/#access" data-cta="demo-embark-${ids[n++] ?? n}"`)
main = main.replace('href="#walkthrough"', 'href="#walkthrough" data-cta="explore-embark-hero"')
// The product film reaches only visitors who have not asked for reduced motion (check-film-motion):
// the server sends its poster, and EmbarkFilm.tsx mounts the <video> into [data-embark-film].
const filmRe = /<video[^>]*poster="([^"]+)"[^>]*data-portrait-poster="([^"]+)"[\s\S]*?<\/video>/
if (!filmRe.test(main)) throw new Error('product film not found in the archived page')
main = main.replace(filmRe, (_, wide, tall) =>
  `<div data-embark-film><picture class="film-poster"><source media="(max-width: 700px)" srcset="${tall}"><img src="${wide}" alt="Embark product tour, first frame: two departures today" width="1200" height="768"></picture></div>`)
main = main.replace(/>Ask about Embark</g, '>Book a 20-minute demo<').replace(/>Contact</g, '>Book a demo<')
writeFileSync('components/clone/butter/embark-body.ts',
  `/* Generated by scripts/clone/port-embark-26.mjs from b25b2b2:public/product-family/embark.html. Do not edit by hand. */\nexport const EMBARK_BODY = ${JSON.stringify(main)}\n`)
console.log(`embark-body.ts: ${main.length} chars, ${n} demo links`)
