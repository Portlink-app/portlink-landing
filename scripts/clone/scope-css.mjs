// Scopes a captured reference stylesheet under one root class so it can sit on a landing route
// next to the site's own CSS without either leaking into the other. Preview-only clone work
// (docs/PRODUCT-PAGES.md "Clone method"): the captured CSS and fonts are third-party and the
// provenance guard refuses them in a production build until they are replaced.
//
//   node scripts/clone/scope-css.mjs <in.css> <out.css> --scope .wb [--rem 10] [--font-dir /clone/waabi/fonts]
//        [--map name=url ...] [--var --color-pink=#176d7a ...]
//
// What it does, in order:
//  1. Unwraps @layer blocks. The landing's design-system CSS is unlayered, and an unlayered rule
//     beats any layered one regardless of specificity, so a layered clone would lose to `p {}`.
//  2. Rewrites rem to px at the reference's root size (--rem, the reference's html font-size) so the
//     clone renders at its own scale while the site keeps 16px for its banner and skip link.
//     Media queries keep 16px per rem: a browser resolves rem there against the initial size.
//  3. Prefixes every selector with the scope class; :root, :host, html and body become the scope.
//  4. Points @font-face urls at local copies and overrides named custom properties (the rebrand).
import { readFileSync, writeFileSync } from 'node:fs'
import postcss from 'postcss'

const [, , input, output, ...rest] = process.argv
const opt = { scope: '.clone', rem: 10, fontDir: '', map: {}, vars: {} }
for (let i = 0; i < rest.length; i += 2) {
  const [k, v] = [rest[i], rest[i + 1]]
  if (k === '--scope') opt.scope = v
  else if (k === '--rem') opt.rem = Number(v)
  else if (k === '--font-dir') opt.fontDir = v
  else if (k === '--map') { const [a, b] = v.split('='); opt.map[a] = b }
  else if (k === '--var') { const j = v.indexOf('='); opt.vars[v.slice(0, j)] = v.slice(j + 1) }
}
if (!input || !output) { console.error('usage: scope-css.mjs <in> <out> --scope .x'); process.exit(1) }

const px = (n, base) => `${+(parseFloat(n) * base).toFixed(3)}px`
const remToPx = (s, base) => s.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => px(n, base))
const S = opt.scope
const scopeSel = (sel) => {
  const t = sel.trim()
  if (/^(:root|:host|html|body)$/.test(t)) return S
  if (/^(:root|html|body)\b/.test(t)) return t.replace(/^(:root|html|body)/, S)
  if (/^(from|to|\d+%)$/.test(t)) return t
  return `${S} ${t}`
}

const root = postcss.parse(readFileSync(input, 'utf8'))
root.walkAtRules('layer', (at) => { if (at.nodes) at.replaceWith(at.nodes); else at.remove() })
root.walkAtRules((at) => { if (at.name === 'media' || at.name === 'supports') at.params = remToPx(at.params, 16) })
root.walkDecls((d) => {
  d.value = remToPx(d.value, opt.rem)
  if (d.parent?.type === 'atrule' && d.parent.name === 'font-face' && d.prop === 'src') {
    // A face with no local copy is dropped: its url would only 404 on our origin.
    const file = (d.value.match(/url\((?:[^)\\]|\\.)*?([^/]+?\.woff2)\)/) || [])[1]?.replace(/\\/g, '')
    if (!file) return
    const local = Object.entries(opt.map).find(([k]) => file.startsWith(k))
    if (local) d.value = `url(${opt.fontDir}/${local[1]}) format("woff2")`
    else d.parent.remove()
  }
})
root.walkRules((r) => {
  if (r.parent?.type === 'atrule' && /keyframes$/.test(r.parent.name)) return
  r.selectors = r.selectors.map(scopeSel)
})
root.walkDecls((d) => { if (d.prop in opt.vars) d.value = opt.vars[d.prop] })
// Rebrand last, so the overrides win over the reference's own declarations of the same names.
const brand = Object.entries(opt.vars).map(([k, v]) => `${k}:${v}`).join(';')
let css = root.toString()
if (brand) css += `\n${S}{${brand}}\n`
writeFileSync(output, `/* Generated by scripts/clone/scope-css.mjs. Do not edit by hand. */\n${css}`)
console.log(`${output}: ${css.length} bytes`)
